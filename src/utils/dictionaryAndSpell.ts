export function checkBanglaSpelling(text: string): SpellCheckResult {
  if (!text) return { hasMistakes: false, mistakes: [] };

  const mistakes: { wrongWord: string; suggestedWord: string; rule: string; index: number }[] = [];

  for (const item of commonBanglaRules) {
    let match: RegExpExecArray | null;
    const regex = new RegExp(item.wrong.source, 'g');
    while ((match = regex.exec(text)) !== null) {
      mistakes.push({
        wrongWord: match[0],
        suggestedWord: item.correct,
        rule: item.rule,
        index: match.index,
      });
    }
  }

  return {
    hasMistakes: mistakes.length > 0,
    mistakes,
  };
}
